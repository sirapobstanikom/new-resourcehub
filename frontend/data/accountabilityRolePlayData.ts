/** กรณี 1–3: manager = ผู้จัดการ, employee = พนักงาน · กรณี 4: manager = ผู้ขอความร่วมมือ, employee = คู่เจรจา */
export const ACCOUNTABILITY_CARDS: Record<
  AccountCaseKey,
  Record<WhaleDoneRole, AccountabilityCard>
> = {
  case1: { manager: CASE1_MANAGER, employee: CASE1_EMPLOYEE },
  case2: { manager: CASE2_MANAGER, employee: CASE2_EMPLOYEE },
  case3: { manager: CASE3_MANAGER, employee: CASE3_EMPLOYEE },
  case4: { manager: CASE4_REQUESTER, employee: CASE4_PEER },
};

export function getAccountabilityCard(
  caseKey: string,
  role: WhaleDoneRole | ''
): AccountabilityCard | null {
  if (!role) return null;
  if (caseKey !== 'case1' && caseKey !== 'case2' && caseKey !== 'case3' && caseKey !== 'case4') {
    return null;
  }
  return ACCOUNTABILITY_CARDS[caseKey as AccountCaseKey][role];
}
