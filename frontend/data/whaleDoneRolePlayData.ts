/** R ทุกระดับมีเนื้อหา; W ทุกระดับ W1–W4 มีเนื้อหา */
export function whaleDoneHasDetail(_role: WhaleDoneRole, scenario: WhaleDoneScenarioId): boolean {
  if (scenario.startsWith('w')) {
    const w = scenario as WhaleDoneW;
    return w === 'w1' || w === 'w2' || w === 'w3' || w === 'w4';
  }
  return true;
}

