/** answers[id] = คะแนนข้อ ก. (0–5) — ข้อ ข. คือ 5 − ค่านั้น */
export type MbtiAnswers = Record<number, number>;

export type MbtiScores = Record<MbtiLetter, number>;

export function calculateMbtiScores(answers: MbtiAnswers): MbtiScores {
  const scores: MbtiScores = { E: 0, I: 0, S: 0, N: 0, T: 0, F: 0, J: 0, P: 0 };
  for (const q of MBTI_QUESTIONS) {
    const a = answers[q.id];
    if (a == null) continue;
    scores[q.aLetter] += a;
    scores[OPPOSITE[q.aLetter]] += MBTI_POINTS_PER_ITEM - a;
  }
  return scores;
}

